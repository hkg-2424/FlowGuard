use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::Arc;
use std::thread::sleep;
use std::time::Duration;
use tracing::{info, warn};

use super::ports::{ActivitySource, SourceError};
use crate::config::FlowGuardConfig;
use crate::domain::{ActivityCapabilities, ActivityObservation, FreshnessState, SourceHealth};
use crate::infrastructure::activitywatch::client::ActivityWatchClient;
use crate::infrastructure::activitywatch::discovery::discover_buckets;
use crate::infrastructure::activitywatch::mapper::check_freshness;
use crate::infrastructure::activitywatch::models::ServerInfo;

/// Structured diagnostic report generated by `flowguard doctor`.
#[derive(Debug, Clone)]
pub struct DoctorReport {
    pub endpoint: String,
    pub is_reachable: bool,
    pub is_activitywatch: bool,
    pub server_info: Option<ServerInfo>,
    pub buckets_count: usize,
    pub window_bucket: Option<String>,
    pub afk_bucket: Option<String>,
    pub web_bucket: Option<String>,
    pub window_freshness: FreshnessState,
    pub idle_freshness: FreshnessState,
    pub browser_freshness: FreshnessState,
    pub capabilities: ActivityCapabilities,
    pub health: SourceHealth,
    pub diagnostics: Vec<String>,
}

/// Orchestrates activity monitoring and exposes domain services to presentation adapters.
pub struct ActivityService {
    source: Box<dyn ActivitySource>,
    config: FlowGuardConfig,
}

impl ActivityService {
    pub fn new(source: Box<dyn ActivitySource>, config: FlowGuardConfig) -> Self {
        Self { source, config }
    }

    /// Performs deep diagnostics on the activity source and returns a structured report.
    pub fn run_doctor(&self) -> DoctorReport {
        let aw_cfg = &self.config.activity_source.activitywatch;
        let endpoint = aw_cfg.base_url.clone();
        let client = ActivityWatchClient::new(
            &endpoint,
            aw_cfg.request_timeout_ms,
            aw_cfg.api_key_env.as_deref(),
        );

        let mut diagnostics = Vec::new();

        // 1. Handshake check
        let server_info = match client.handshake() {
            Ok(info) => {
                if info.testing {
                    diagnostics.push(
                        "Notice: ActivityWatch server is running in testing/dev mode.".to_string(),
                    );
                }
                Some(info)
            }
            Err(e) => {
                diagnostics.push(format!("Handshake failed: {}", e));
                return DoctorReport {
                    endpoint,
                    is_reachable: false,
                    is_activitywatch: false,
                    server_info: None,
                    buckets_count: 0,
                    window_bucket: None,
                    afk_bucket: None,
                    web_bucket: None,
                    window_freshness: FreshnessState::Missing,
                    idle_freshness: FreshnessState::Missing,
                    browser_freshness: FreshnessState::Missing,
                    capabilities: ActivityCapabilities::none(),
                    health: match e {
                        SourceError::WrongService { .. } => SourceHealth::WrongService,
                        _ => SourceHealth::Disconnected,
                    },
                    diagnostics,
                };
            }
        };

        let hostname = server_info
            .as_ref()
            .map(|s| s.hostname.clone())
            .unwrap_or_default();

        // 2. Discover buckets
        let all_buckets = match client.get_buckets() {
            Ok(b) => b,
            Err(e) => {
                diagnostics.push(format!("Bucket discovery failed: {}", e));
                return DoctorReport {
                    endpoint,
                    is_reachable: true,
                    is_activitywatch: true,
                    server_info,
                    buckets_count: 0,
                    window_bucket: None,
                    afk_bucket: None,
                    web_bucket: None,
                    window_freshness: FreshnessState::Missing,
                    idle_freshness: FreshnessState::Missing,
                    browser_freshness: FreshnessState::Missing,
                    capabilities: ActivityCapabilities::none(),
                    health: SourceHealth::Degraded,
                    diagnostics,
                };
            }
        };

        let buckets_count = all_buckets.len();
        let discovered =
            discover_buckets(&all_buckets, &hostname, aw_cfg.bucket_overrides.as_ref());
        diagnostics.extend(discovered.diagnostics.clone());

        // 3. Check Freshness of Discovered Buckets
        let now = chrono::Utc::now();

        let (window_freshness, window_age) = if let Some(ref bid) = discovered.window_bucket {
            match client.get_latest_event(bid) {
                Ok(ev) => check_freshness(ev.as_ref(), now, aw_cfg.stale_after_secs),
                Err(e) => {
                    diagnostics.push(format!("Failed to query latest window event: {}", e));
                    (FreshnessState::Missing, None)
                }
            }
        } else {
            (FreshnessState::Missing, None)
        };

        if window_freshness == FreshnessState::Stale {
            diagnostics.push(format!(
                "Window watcher event is stale (age: {}s, threshold: {}s). Ensure aw-watcher-window is running.",
                window_age.unwrap_or(0),
                aw_cfg.stale_after_secs
            ));
        }

        let (idle_freshness, idle_age) = if let Some(ref bid) = discovered.afk_bucket {
            match client.get_latest_event(bid) {
                Ok(ev) => check_freshness(ev.as_ref(), now, aw_cfg.stale_after_secs),
                Err(e) => {
                    diagnostics.push(format!("Failed to query latest AFK event: {}", e));
                    (FreshnessState::Missing, None)
                }
            }
        } else {
            (FreshnessState::Missing, None)
        };

        if idle_freshness == FreshnessState::Stale {
            diagnostics.push(format!(
                "AFK watcher event is stale (age: {}s). Ensure aw-watcher-afk is running.",
                idle_age.unwrap_or(0)
            ));
        }

        let (browser_freshness, _) = if let Some(ref bid) = discovered.web_bucket {
            match client.get_latest_event(bid) {
                Ok(ev) => check_freshness(ev.as_ref(), now, aw_cfg.stale_after_secs),
                Err(e) => {
                    diagnostics.push(format!("Failed to query latest web event: {}", e));
                    (FreshnessState::Missing, None)
                }
            }
        } else {
            (FreshnessState::Missing, None)
        };

        let capabilities = ActivityCapabilities {
            application_tracking: window_freshness == FreshnessState::Fresh,
            window_title_tracking: window_freshness == FreshnessState::Fresh,
            idle_tracking: idle_freshness == FreshnessState::Fresh,
            browser_url_tracking: browser_freshness == FreshnessState::Fresh,
            incognito_detection: browser_freshness == FreshnessState::Fresh,
        };

        let health = if window_freshness == FreshnessState::Fresh
            && idle_freshness == FreshnessState::Fresh
        {
            SourceHealth::Connected
        } else {
            SourceHealth::Degraded
        };

        DoctorReport {
            endpoint,
            is_reachable: true,
            is_activitywatch: true,
            server_info,
            buckets_count,
            window_bucket: discovered.window_bucket,
            afk_bucket: discovered.afk_bucket,
            web_bucket: discovered.web_bucket,
            window_freshness,
            idle_freshness,
            browser_freshness,
            capabilities,
            health,
            diagnostics,
        }
    }

    /// Queries source operational status and capabilities.
    pub fn status(&mut self) -> (SourceHealth, ActivityCapabilities) {
        match self.source.poll() {
            Ok(obs) => (obs.source_health, obs.capabilities),
            Err(_) => (self.source.health(), ActivityCapabilities::none()),
        }
    }

    /// Fetches one immediate activity observation.
    pub fn observe_once(&mut self) -> Result<ActivityObservation, SourceError> {
        self.source.poll()
    }

    /// Starts a continuous observation loop.
    ///
    /// Periodically polls the activity source according to `poll_interval_ms`.
    /// When state changes are detected, `on_change` is invoked.
    /// Temporary connection failures trigger bounded backoff retries without exiting.
    /// Gracefully exits when `running` is set to false (e.g. on Ctrl+C).
    pub fn observe<F>(
        &mut self,
        running: Arc<AtomicBool>,
        mut on_change: F,
    ) -> Result<(), SourceError>
    where
        F: FnMut(&ActivityObservation),
    {
        let poll_interval =
            Duration::from_millis(self.config.activity_source.activitywatch.poll_interval_ms);
        let reconnect_interval = Duration::from_secs(
            self.config
                .activity_source
                .activitywatch
                .reconnect_interval_secs,
        );

        let mut previous_observation: Option<ActivityObservation> = None;

        info!("Starting continuous activity observation loop...");

        while running.load(Ordering::SeqCst) {
            match self.source.poll() {
                Ok(obs) => {
                    let should_notify = match &previous_observation {
                        Some(prev) => obs.has_meaningful_change(prev),
                        None => true,
                    };

                    if should_notify {
                        on_change(&obs);
                        previous_observation = Some(obs);
                    }

                    // Wait for the next poll cycle
                    sleep(poll_interval);
                }
                Err(err) => {
                    warn!(
                        "Error during observation cycle: {}. Will retry in {}s...",
                        err,
                        reconnect_interval.as_secs()
                    );
                    let disconnected_obs = ActivityObservation::disconnected(
                        SourceHealth::Disconnected,
                        vec![format!("Observation error: {}", err)],
                    );

                    let should_notify = match &previous_observation {
                        Some(prev) => disconnected_obs.has_meaningful_change(prev),
                        None => true,
                    };

                    if should_notify {
                        on_change(&disconnected_obs);
                        previous_observation = Some(disconnected_obs);
                    }

                    // Wait for configured reconnect interval before retrying
                    sleep(reconnect_interval);
                }
            }
        }

        info!("Observation loop exited gracefully.");
        Ok(())
    }
}
